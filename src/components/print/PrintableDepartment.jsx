/** Cover page for the consolidated department report (A4 portrait). */
export default function PrintableDepartment({ analytics, settings, store }) {
  const kpis = analytics?.kpis ?? {};
  const signatures = (settings?.signatures ?? []).slice(0, 3);

  return (
    <section className="print-page print-page-portrait print-cover">
      <header className="print-doc-header">
        <h1 className="print-institute">{settings?.instituteName}</h1>
        <p className="print-department">{settings?.departmentName}</p>
        <div className="print-meta-bar">
          <span className="print-meta-item">
            <span className="print-meta-label">Document</span>
            <span className="print-meta-value">Department Timetable Report</span>
          </span>
          <span className="print-meta-item">
            <span className="print-meta-label">Semester</span>
            <span className="print-meta-value">
              {store?.academicYear ?? settings?.academicYear} ·{' '}
              {store?.termType ?? settings?.semester}
            </span>
          </span>
          <span className="print-meta-item">
            <span className="print-meta-label">W.E.F.</span>
            <span className="print-meta-value">{settings?.wefDate ?? '—'}</span>
          </span>
        </div>
      </header>

      <h2 className="print-cover-title">Weekly Timetable &amp; Utilisation Summary</h2>
      <p className="print-cover-copy">
        This report contains the weekly timetable for every division, followed by the
        department utilisation and faculty load summary. It is generated from the saved
        plan and the current Master Data.
      </p>

      <div className="print-cover-kpis">
        <div>
          <span>Sessions</span>
          <strong>{kpis.totalSessions ?? 0}</strong>
          <small>
            {kpis.theorySessions ?? 0} theory · {kpis.practicalSessions ?? 0} practical
          </small>
        </div>
        <div>
          <span>Average faculty load</span>
          <strong>{Math.round(kpis.averageLoadPercent ?? 0)}%</strong>
          <small>{kpis.cappedFacultyCount ?? 0} faculty with a cap</small>
        </div>
        <div>
          <span>Classroom utilisation</span>
          <strong>{Math.round(kpis.classroomPercent ?? 0)}%</strong>
          <small>
            {kpis.classroomBooked ?? 0} / {kpis.classroomCapacity ?? 0} slots
          </small>
        </div>
        <div>
          <span>Lab utilisation</span>
          <strong>{Math.round(kpis.labPercent ?? 0)}%</strong>
          <small>
            {kpis.labBooked ?? 0} / {kpis.labCapacity ?? 0} blocks
          </small>
        </div>
      </div>

      <div className="print-cover-divisions">
        <h3>Divisions in this report</h3>
        <ul>
          {(analytics?.divisionNames ?? []).map((name) => (
            <li key={name}>{name}</li>
          ))}
        </ul>
      </div>

      <div className="print-workload-signatures">
        {signatures.map((label) => (
          <div key={label} className="print-signature">
            <span className="print-signature-line" />
            <span className="print-signature-label">{label}</span>
          </div>
        ))}
      </div>
      <footer className="print-footer">
        {store?.name ?? ''} · Generated by Timetable Studio
      </footer>
    </section>
  );
}
